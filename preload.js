const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  state: () => ipcRenderer.invoke('state'),
  rate: (key, stars) => ipcRenderer.invoke('rate', key, stars),
  scan: () => ipcRenderer.invoke('scan'),
  addDir: () => ipcRenderer.invoke('add-dir'),
  removeDir: (d) => ipcRenderer.invoke('remove-dir', d),
  setConfig: (p) => ipcRenderer.invoke('set-config', p),
  play: (opts) => ipcRenderer.invoke('play', opts),
  setWatched: (ids, watched) => ipcRenderer.invoke('set-watched', { ids, watched }),
  reveal: (p) => ipcRenderer.invoke('reveal', p),
  audioDevices: () => ipcRenderer.invoke('audio-devices'),
  remoteInfo: () => ipcRenderer.invoke('remote-info'),
  drives: () => ipcRenderer.invoke('drives'),
  copyDrive: (mount) => ipcRenderer.invoke('drive-copy', mount),
  cancelCopy: () => ipcRenderer.invoke('drive-copy-cancel'),
  ejectDrive: (mount) => ipcRenderer.invoke('drive-eject', mount),
  onDrivesChanged: (cb) => ipcRenderer.on('drives-changed', (_e, m) => cb(m)),
  onCopyProgress: (cb) => ipcRenderer.on('copy-progress', (_e, m) => cb(m)),
  wifiStatus: () => ipcRenderer.invoke('wifi-status'),
  wifiScan: () => ipcRenderer.invoke('wifi-scan'),
  wifiConnect: (ssid, pw) => ipcRenderer.invoke('wifi-connect', ssid, pw),
  btStatus: () => ipcRenderer.invoke('bt-status'),
  btScan: () => ipcRenderer.invoke('bt-scan'),
  btPair: (mac) => ipcRenderer.invoke('bt-pair', mac),
  btConnect: (mac) => ipcRenderer.invoke('bt-connect', mac),
  btRemove: (mac) => ipcRenderer.invoke('bt-remove', mac),
  applianceInfo: () => ipcRenderer.invoke('appliance-info'),
  applianceUpdate: () => ipcRenderer.invoke('appliance-update'),
  selectProfile: (id, pin) => ipcRenderer.invoke('profile-select', id, pin),
  showProfilePicker: () => ipcRenderer.invoke('profile-picker'),
  saveProfile: (profile, pin) => ipcRenderer.invoke('profile-save', profile, pin),
  setProfilePin: (id, newPin, pin) => ipcRenderer.invoke('profile-set-pin', id, newPin, pin),
  deleteProfile: (id, pin) => ipcRenderer.invoke('profile-delete', id, pin),
  quit: () => ipcRenderer.invoke('quit'),
  power: (action) => ipcRenderer.invoke('power', action),
  onScanProgress: (cb) => ipcRenderer.on('scan-progress', (_e, p) => cb(p)),
  onLibraryUpdated: (cb) => ipcRenderer.on('library-updated', (_e, s) => cb(s)),
  onRemote: (cb) => ipcRenderer.on('remote', (_e, m) => cb(m)),
  onPlaybackError: (cb) => ipcRenderer.on('playback-error', (_e, m) => cb(m)),
  onPlaybackEnded: (cb) => ipcRenderer.on('playback-ended', (_e, s) => cb(s)),
  onConfigChanged: (cb) => ipcRenderer.on('config-changed', (_e, s) => cb(s)),
  // Parlor (music)
  parlorState: () => ipcRenderer.invoke('parlor-state'),
  parlorRescan: () => ipcRenderer.invoke('parlor-rescan'),
  parlorAddDir: (dir) => ipcRenderer.invoke('parlor-add-dir', dir || null),
  parlorRemoveDir: (dir) => ipcRenderer.invoke('parlor-remove-dir', dir),
  parlorShare: (albumKey, pid, on) => ipcRenderer.invoke('parlor-share', albumKey, pid, on),
  parlorCoverSearch: (key) => ipcRenderer.invoke('parlor-cover-search', key),
  parlorCoverSet: (key, choice) => ipcRenderer.invoke('parlor-cover-set', key, choice || null),
  parlorCoversAuto: () => ipcRenderer.invoke('parlor-covers-auto'),
  playlistCreate: (name, trackIds) => ipcRenderer.invoke('playlist-create', name, trackIds),
  playlistUpdate: (id, patch) => ipcRenderer.invoke('playlist-update', id, patch),
  playlistDelete: (id) => ipcRenderer.invoke('playlist-delete', id),
  musicPlay: (req) => ipcRenderer.invoke('music-play', req),
  musicCmd: (cmd, arg) => ipcRenderer.invoke('music-cmd', cmd, arg),
  onMusicState: (cb) => ipcRenderer.on('music-state', (_e, s) => cb(s)),
  onParlorUpdated: (cb) => ipcRenderer.on('parlor-updated', () => cb()),
});
